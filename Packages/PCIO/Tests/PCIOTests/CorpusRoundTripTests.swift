// Round trips of the Photoshop corpus: import → Document → export → re-import, with the checks
// that every typed block survives, that ImageIO opens the export, that the composite passed in is
// what ImageIO shows, and that PCPSD's Photoshop-compatibility linter finds nothing.
// New (photocraft's corpus tests need its external corpus); MIT OR Apache-2.0, © ArtCraft Team and
// the PhotoCraft contributors.

import CoreGraphics
import Foundation
import ImageIO
import PCDocument
import PCFoundation
import PCIOCore
import PCPSD
import Testing
@testable import PCIO

@Suite(.serialized) struct CorpusRoundTripTests {
    init() { ExportSweep.install() }
    struct Outcome {
        var name: String
        var layers = 0
        var diffs: [String] = []
        var blocksChecked = 0
        var blocksLost: [String] = []
        var globalsLost: [String] = []
        var resourcesLost: [String] = []
        var imageIOOpens = false
        var imageIOMaxDiff = 255
        var compositeMaxDiff: Float = 1
        var lintErrors: [String] = []
        var lintWarnings: [String] = []
        var warnings: [String] = []
        var secondGenStable = false
        var secondGenDetail = ""
        /// Whether ImageIO reads this mode at all (it can't open Lab, Indexed or Multichannel).
        var imageIOApplies = true
        /// Whether ImageIO's pixels are compared (RGB).
        var imageIOCompares = true
        /// A failure that stopped this file's round trip.
        var error: String?
        /// The layer record count changed (a flattened file gains its Background layer).
        var recordCount: String?
    }

    /// One file through the whole round trip.
    static func roundTrip(_ url: URL) throws -> Outcome {
        var o = Outcome(name: url.lastPathComponent)
        let file = try PSDFile(contentsOf: url)
        let imported = try DocumentIO.importFile(contentsOf: url, options: IOOptions(compositor: StoredPixelsCompositor()))
        let doc = imported.document
        doc.forEachLayer { _, _, _ in o.layers += 1 }
        // The composite passed in: Photoshop's own merged image (un-matted).
        let px = try mergedPixels(file, doc)
        let compositor = FixedCompositor(pixels: px, size: doc.size)
        let options = IOOptions(compositor: compositor)
        let exported = try ExportSweep.$name.withValue(Corpus.sweepName(url, ".reexport.\(url.pathExtension.lowercased() == "psb" ? "psb" : "psd")")) {
            try DocumentIO.export(doc, as: url.lastPathComponent, options: options)
        }
        o.warnings = exported.warnings
        let back = try PSDFile(bytes: exported.bytes)
        // Photoshop-compatibility linter (structure + decoded channels).
        for issue in back.compatibilityIssues(decodeChannels: true) {
            if issue.severity == .error { o.lintErrors.append(issue.description) } else { o.lintWarnings.append(issue.description) }
        }
        // Re-import equals.
        let re = try DocumentIO.importFile(name: url.lastPathComponent, bytes: exported.bytes, options: IOOptions(compositor: StoredPixelsCompositor()))
        o.diffs = DocDiff.of(doc, re.document)
        // Every typed block of every original record survives (data byte-identical), by record.
        let origRecords = file.layers, newRecords = back.layers
        if origRecords.count == newRecords.count {
            for (a, b) in zip(origRecords, newRecords) {
                for blk in a.blocks where !["luni", "lyid", "lsct", "lsdk", "iOpa", "lspf", "lclr"].contains(blk.key) {
                    o.blocksChecked += 1
                    if !b.blocks.contains(where: { $0.key == blk.key && $0.data == blk.data }) {
                        // Regenerated-from-model blocks must at least decode the same.
                        o.blocksLost.append("\(a.displayName): \(blk.key)")
                    }
                }
            }
        } else {
            // A flattened file (no layer records) opens as a Background layer and is saved with it.
            o.recordCount = "record count \(origRecords.count) → \(newRecords.count)"
        }
        for g in file.globalBlocks where !back.globalBlocks.contains(where: { $0.key == g.key && $0.data.starts(with: g.data) }) {
            o.globalsLost.append(g.key.string)
        }
        // Regenerated by design: thumbnails (rendered from the composite), version info, the
        // target layer and selection ids (UI state), XMP/EXIF (normalised, see DocDiff).
        let regeneratedResources: Set<UInt16> = [PSDResourceID.thumbnail, PSDResourceID.thumbnailPS4, PSDResourceID.versionInfo, PSDResourceID.layerState,
                                                  1069, 1072, PSDResourceID.xmp, PSDResourceID.exif]
        for r in file.resources where !regeneratedResources.contains(r.id) {
            if !back.resources.contains(where: { $0.id == r.id && $0.data == r.data }) { o.resourcesLost.append("\(r.id)") }
        }
        // ImageIO opens the export and shows the composite we passed in (8-bit RGB keeps
        // Photoshop's white matte; compare against our own stored merged data).
        o.imageIOApplies = [.rgb, .grayscale, .cmyk].contains(back.header.colorMode) && back.header.depth != 1
        // ImageIO colour-manages Gray and CMYK (gray gamma, CMYK profile) where PCPSD's preview
        // converts naively: the pixel comparison is meaningful for RGB.
        o.imageIOCompares = back.header.colorMode == .rgb
        if o.imageIOApplies, let io = imageIORGBA8(exported.bytes), io.width == Int(back.header.width), io.height == Int(back.header.height) {
            o.imageIOOpens = true
            // ImageIO returns the stored (white-matted) merged colour premultiplied by the merged
            // alpha: compare against our stored merged data the same way.
            let ours = try back.compositeRGBA8(unmatte: false)
            var m = 0
            for i in 0 ..< io.width * io.height {
                let a = Int(ours.data[i * 4 + 3])
                m = max(m, abs(Int(io.data[i * 4 + 3]) - a))
                for c in 0 ..< 3 {
                    let want = (Int(ours.data[i * 4 + c]) * a + 127) / 255
                    m = max(m, abs(Int(io.data[i * 4 + c]) - want))
                }
            }
            o.imageIOMaxDiff = m
        }
        // The merged image written equals the composite passed in.
        let written = try mergedPixels(back, doc)
        var dm: Float = 0
        for (a, b) in zip(written, px) where a.isFinite && b.isFinite { dm = max(dm, abs(a - b)) }
        o.compositeMaxDiff = dm
        // A second generation writes the same layer records (fixed point).
        let again = try ExportSweep.$name.withValue("") { try DocumentIO.export(re.document, as: url.lastPathComponent, options: options) }
        let gen2 = try PSDFile(bytes: again.bytes)
        o.secondGenStable = gen2.layers == back.layers
        if !o.secondGenStable {
            for (k, (a, b)) in zip(back.layers, gen2.layers).enumerated() where a != b {
                let changed = zip(a.blocks, b.blocks).filter { $0 != $1 }.map { "\($0.0.key): \([UInt8]($0.0.data).prefix(24)) → \([UInt8]($0.1.data).prefix(24))" }
                o.secondGenDetail = "gen2 record \(k) \(a.displayName): \(changed) flags \(a.flags.rawValue)/\(b.flags.rawValue) opacity \(a.opacity)/\(b.opacity) blend \(a.blendMode)/\(b.blendMode) ranges \(a.blendingRanges == b.blendingRanges) rect \(a.rect)/\(b.rect) mask \(a.mask == b.mask)"
                break
            }
        }
        return o
    }

    /// Runs every file of a corpus, printing `MEASURE <label> …` lines; returns the outcomes.
    static func run(_ label: String, _ files: [URL]) -> [Outcome] {
        var outcomes: [Outcome] = []
        for url in files {
            do { outcomes.append(try CorpusRoundTripTests.roundTrip(url)) } catch {
                var o = Outcome(name: url.lastPathComponent)
                o.error = "\(error)"
                outcomes.append(o)
            }
        }
        let ok = outcomes.filter { $0.error == nil }
        let n = outcomes.count
        let equal = ok.filter { $0.diffs.isEmpty }.count
        let blocks = ok.reduce(0) { $0 + $1.blocksChecked }
        let lost = ok.reduce(0) { $0 + $1.blocksLost.count }
        let ioFiles = ok.filter(\.imageIOApplies)
        let opens = ioFiles.filter(\.imageIOOpens).count
        let ioCompared = ioFiles.filter(\.imageIOCompares)
        let ioExact = ioCompared.filter { $0.imageIOMaxDiff <= 1 }.count
        let compExact = ok.filter { $0.compositeMaxDiff <= 0.5 / 255 }.count
        let clean = ok.filter { $0.lintErrors.isEmpty }.count
        let stable = ok.filter(\.secondGenStable).count
        let globalsOK = ok.filter { $0.globalsLost.isEmpty }.count
        let resourcesOK = ok.filter { $0.resourcesLost.isEmpty }.count
        print("MEASURE \(label) round trip: \(n) files, \(ok.reduce(0) { $0 + $1.layers }) layers; failed to round-trip: \(n - ok.count)")
        print("MEASURE   re-import equal: \(equal)/\(n)")
        print("MEASURE   layer blocks byte-identical: \(blocks - lost)/\(blocks)")
        print("MEASURE   global blocks kept: \(globalsOK)/\(n) files; resources kept: \(resourcesOK)/\(n) files")
        print("MEASURE   ImageIO opens: \(opens)/\(ioFiles.count) (modes ImageIO reads); ImageIO composite within 1 level (RGB, premultiplied 8-bit rounding): \(ioExact)/\(ioCompared.count), max \(ioCompared.map(\.imageIOMaxDiff).max() ?? 0); merged image = composite passed in: \(compExact)/\(n)")
        print("MEASURE   linter clean (0 errors): \(clean)/\(n); warnings: \(ok.reduce(0) { $0 + $1.lintWarnings.count })")
        print("MEASURE   second generation layer records identical: \(stable)/\(n)")
        let flattened = ok.filter { $0.recordCount != nil }.count
        if flattened > 0 { print("MEASURE   flattened files saved with their Background layer: \(flattened)") }
        for o in outcomes where o.error != nil || !o.diffs.isEmpty || !o.secondGenStable || !o.blocksLost.isEmpty || !o.lintErrors.isEmpty || !o.globalsLost.isEmpty
            || !o.resourcesLost.isEmpty || o.recordCount != nil || (o.imageIOApplies && o.imageIOCompares && o.imageIOMaxDiff > 1) || o.compositeMaxDiff > 0.5 / 255 {
            if let e = o.error { print("DETAIL \(label) \(o.name): error \(e)"); continue }
            var parts: [String] = []
            if let r = o.recordCount { parts.append(r) }
            if !o.diffs.isEmpty { parts.append("diffs \(o.diffs.prefix(4))") }
            if !o.blocksLost.isEmpty { parts.append("blocks \(o.blocksLost.prefix(6))") }
            if !o.globalsLost.isEmpty { parts.append("globals \(o.globalsLost)") }
            if !o.resourcesLost.isEmpty { parts.append("resources \(o.resourcesLost)") }
            if !o.lintErrors.isEmpty { parts.append("lint \(o.lintErrors.prefix(3))") }
            if !o.secondGenStable { parts.append(o.secondGenDetail) }
            if o.imageIOApplies, o.imageIOCompares, o.imageIOMaxDiff > 1 { parts.append("ImageIO max diff \(o.imageIOMaxDiff)") }
            if o.compositeMaxDiff > 0.5 / 255 { parts.append("merged vs passed \(o.compositeMaxDiff)") }
            print("DETAIL \(label) \(o.name): \(parts.joined(separator: "; "))")
        }
        let warnings = Set(ok.flatMap(\.warnings))
        for w in warnings.sorted().prefix(20) { print("WARN \(label) \(w)") }
        return outcomes
    }

    @Test(.enabled(if: Corpus.available, "PSD corpus not present (set PHOTOCRAFT_FIXTURES or PCPSD_CORPUS)")) func corpusRoundTrips() throws {
        let outcomes = CorpusRoundTripTests.run("psd-corpus", Corpus.files)
        let n = outcomes.count
        #expect(outcomes.allSatisfy { $0.error == nil })
        #expect(outcomes.filter { $0.diffs.isEmpty }.count == n)
        #expect(outcomes.reduce(0) { $0 + $1.blocksLost.count } == 0)
        #expect(outcomes.filter(\.imageIOOpens).count == n)
        #expect(outcomes.filter { $0.imageIOMaxDiff <= 1 }.count == n)
        #expect(outcomes.filter { $0.compositeMaxDiff <= 0.5 / 255 }.count == n)
        #expect(outcomes.filter { $0.lintErrors.isEmpty }.count == n)
        #expect(outcomes.filter(\.secondGenStable).count == n)
    }

    /// The Photoshop-generated corpus (every mode and depth, PSB, …): measured and reported; only
    /// a file that fails to import or export at all is a test failure.
    @Test(.enabled(if: Corpus.psAvailable, "Photoshop corpus not present (set PHOTOCRAFT_FIXTURES or PCIO_PS_CORPUS)")) func photoshopCorpusRoundTrips() throws {
        let outcomes = CorpusRoundTripTests.run("ps-corpus", Corpus.psFiles)
        for o in outcomes where o.error != nil { Issue.record("\(o.name): \(o.error ?? "")") }
    }
}
